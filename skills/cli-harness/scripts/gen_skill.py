"""Render a harness SKILL.md from cli.py (parsed with ast, never executed) and harness.json."""
import argparse
import ast
import json
import sys
from pathlib import Path


def _dotted(node):
    if isinstance(node, ast.Call):
        node = node.func
    if isinstance(node, ast.Attribute) and isinstance(node.value, ast.Name):
        return f"{node.value.id}.{node.attr}"
    return None


def _str_args(call):
    if not isinstance(call, ast.Call):
        return []
    return [a.value for a in call.args if isinstance(a, ast.Constant) and isinstance(a.value, str)]


def _kwarg(call, key):
    if isinstance(call, ast.Call):
        for kw in call.keywords:
            if kw.arg == key and isinstance(kw.value, ast.Constant) and isinstance(kw.value.value, str):
                return kw.value.value
    return None


def _options(func):
    opts = []
    for dec in func.decorator_list:
        if _dotted(dec) == "click.option":
            strs = _str_args(dec)
            flag = next((s for s in strs if s.startswith("--")), strs[0] if strs else "")
            opts.append({"flag": flag, "help": _kwarg(dec, "help") or ""})
    return opts


def _arguments(func):
    return [s[0] for d in func.decorator_list if _dotted(d) == "click.argument" and (s := _str_args(d))]


def _help(func):
    doc = ast.get_docstring(func)
    return doc.splitlines()[0].strip() if doc else ""


def parse_cli(source):
    funcs = [n for n in ast.walk(ast.parse(source))
             if isinstance(n, (ast.FunctionDef, ast.AsyncFunctionDef))]
    funcs.sort(key=lambda n: (n.lineno, n.col_offset))
    group = next((f for f in funcs if any(_dotted(d) == "click.group" for d in f.decorator_list)), None)
    group_name = group.name if group else None
    commands = []
    for f in funcs:
        for dec in f.decorator_list:
            d = _dotted(dec)
            if d == "click.command" or (group_name and d == f"{group_name}.command"):
                strs = _str_args(dec)
                name = (strs[0] if strs else None) or _kwarg(dec, "name") or f.name.replace("_", "-")
                commands.append({"name": name, "func": f.name, "help": _help(f),
                                 "options": _options(f), "arguments": _arguments(f)})
                break
    return {"group": group_name, "group_options": _options(group) if group else [],
            "commands": commands}


def _cell(text):
    return text.replace("|", "\\|")


def render_skill(meta, parsed):
    binary = meta["binary"]
    mutating = ", ".join(meta.get("mutating") or []) or "none"
    lines = [
        "---",
        f"name: {binary}-harness",
        f"description: Agent harness for the {binary} CLI ({meta['version']}). {meta['description']}",
        "---",
        "",
        f"# {binary} harness",
        "",
        "Generated by cli-harness gen_skill.py from cli.py. Do not edit by hand.",
        "",
        "## Rules for agents",
        "- Invoke as `python3 cli.py --json <command> [ARGS] [OPTIONS]`. The --json flag goes before the command name.",
        "- Parse stdout as JSON.",
        f"- Run any mutating command with --dry-run first: {mutating}.",
        "- Non-zero exit means failure. Never treat exit 0 alone as proof the output is right.",
        "",
        "## Commands",
        "| Command | Description | Options | Arguments |",
        "|---|---|---|---|",
    ]
    for c in parsed["commands"]:
        opts = ", ".join(o["flag"] for o in c["options"]) or "-"
        args = ", ".join(c["arguments"]) or "-"
        lines.append(f"| {_cell(c['name'])} | {_cell(c['help'])} | {_cell(opts)} | {_cell(args)} |")
    return "\n".join(lines) + "\n"


def render_dir(harness_dir):
    d = Path(harness_dir)
    meta = json.loads((d / "harness.json").read_text())
    return render_skill(meta, parse_cli((d / "cli.py").read_text()))


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("harness_dir")
    ap.add_argument("--check", action="store_true", help="write nothing; exit 1 if SKILL.md is stale")
    args = ap.parse_args(argv)
    target = Path(args.harness_dir) / "SKILL.md"
    fresh = render_dir(args.harness_dir)
    if args.check:
        if target.exists() and target.read_text() == fresh:
            return 0
        print("SKILL.md is stale")
        return 1
    target.write_text(fresh)
    return 0


if __name__ == "__main__":
    sys.exit(main())
