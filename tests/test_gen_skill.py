import json

import pytest

CLI_SRC = '''import click

raise SystemExit("must not execute")


@click.group()
@click.option("--json", "as_json", is_flag=True, help="Machine-readable JSON output.")
def cli(as_json):
    """Root group."""


@cli.command("list-all")
def lister():
    """List everything.

    More detail here.
    """


@cli.command()
def make_thing():
    """Make a thing."""


@cli.command()
@click.argument("name")
@click.option("--force", "-f", is_flag=True, help="Force it.")
@click.option("--dry-run", is_flag=True, help="Preview only.")
@click.option("--quiet", is_flag=True)
def create(name, force, dry_run, quiet):
    """Create something."""
'''

EXPECTED = {
    "group": "cli",
    "group_options": [{"flag": "--json", "help": "Machine-readable JSON output."}],
    "commands": [
        {"name": "list-all", "func": "lister", "help": "List everything.", "options": [], "arguments": []},
        {"name": "make-thing", "func": "make_thing", "help": "Make a thing.", "options": [], "arguments": []},
        {
            "name": "create",
            "func": "create",
            "help": "Create something.",
            "options": [
                {"flag": "--force", "help": "Force it."},
                {"flag": "--dry-run", "help": "Preview only."},
                {"flag": "--quiet", "help": ""},
            ],
            "arguments": ["name"],
        },
    ],
}

META = {"binary": "demo", "version": "1.2.3", "description": "Demo wrapper.", "mutating": ["create"]}

EXPECTED_MD = """---
name: demo-harness
description: Agent harness for the demo CLI (1.2.3). Demo wrapper.
---

# demo harness

Generated by cli-harness gen_skill.py from cli.py. Do not edit by hand.

## Rules for agents
- Invoke as `python3 cli.py --json <command> [ARGS] [OPTIONS]`. The --json flag goes before the command name.
- Parse stdout as JSON.
- Run any mutating command with --dry-run first: create.
- Non-zero exit means failure. Never treat exit 0 alone as proof the output is right.

## Commands
| Command | Description | Options | Arguments |
|---|---|---|---|
| list-all | List everything. | - | - |
| make-thing | Make a thing. | - | - |
| create | Create something. | --force, --dry-run, --quiet | name |
"""


@pytest.fixture
def gs(SCRIPTS, load_module):
    return load_module(SCRIPTS / "gen_skill.py")


def test_parse_cli_exact(gs):
    assert gs.parse_cli(CLI_SRC) == EXPECTED


def test_parse_cli_click_command_decorator(gs):
    src = 'import click\n\n@click.command("solo")\n@click.option("-v", "--verbose")\ndef main_fn():\n    """Solo."""\n'
    r = gs.parse_cli(src)
    assert r["group"] is None
    assert r["commands"][0]["name"] == "solo"
    assert r["commands"][0]["options"] == [{"flag": "--verbose", "help": ""}]


def test_render_deterministic_and_format(gs):
    parsed = gs.parse_cli(CLI_SRC)
    a = gs.render_skill(META, parsed)
    b = gs.render_skill(META, parsed)
    assert a == b
    assert a == EXPECTED_MD
    assert a.endswith("\n") and not a.endswith("\n\n")


def test_render_no_mutating(gs):
    meta = dict(META, mutating=[])
    out = gs.render_skill(meta, gs.parse_cli(CLI_SRC))
    assert "first: none." in out


def _harness(tmp_path):
    d = tmp_path / "harness-demo"
    d.mkdir()
    (d / "cli.py").write_text(CLI_SRC)
    (d / "harness.json").write_text(json.dumps(META))
    return d


def test_cli_writes_skill_md(SCRIPTS, run_script, tmp_path):
    d = _harness(tmp_path)
    p = run_script(SCRIPTS / "gen_skill.py", d)
    assert p.returncode == 0, p.stderr
    assert (d / "SKILL.md").read_text() == EXPECTED_MD


def test_check_fresh_then_stale(SCRIPTS, run_script, tmp_path):
    d = _harness(tmp_path)
    assert run_script(SCRIPTS / "gen_skill.py", d).returncode == 0
    p = run_script(SCRIPTS / "gen_skill.py", d, "--check")
    assert p.returncode == 0, p.stdout + p.stderr
    with open(d / "SKILL.md", "a") as f:
        f.write("hand edit\n")
    p = run_script(SCRIPTS / "gen_skill.py", d, "--check")
    assert p.returncode == 1
    assert "SKILL.md is stale" in p.stdout + p.stderr
    assert (d / "SKILL.md").read_text().endswith("hand edit\n")  # --check writes nothing
